import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const packageJson = JSON.parse(readFileSync("package.json", "utf8"));
const version = packageJson.version;

if (!version) {
  console.error("Missing package version in package.json");
  process.exit(1);
}

const tag = `v${version}`;
const releaseExists = runQuiet("gh", ["release", "view", tag]);

if (releaseExists) {
  console.log(`GitHub release ${tag} already exists, skipping.`);
  process.exit(0);
}

const token = process.env.GH_TOKEN ?? process.env.GITHUB_TOKEN;

if (!token) {
  console.error("GH_TOKEN or GITHUB_TOKEN is required to create a release.");
  process.exit(1);
}

const notes = getReleaseNotes(version);
const tempDir = mkdtempSync(join(tmpdir(), "creator-inbox-release-"));
const notesPath = join(tempDir, "notes.md");

writeFileSync(notesPath, `${notes.trim()}\n`, "utf8");

run("gh", ["release", "create", tag, "--title", tag, "--notes-file", notesPath], {
  env: {
    ...process.env,
    GH_TOKEN: token,
  },
});

rmSync(tempDir, { recursive: true, force: true });

function getReleaseNotes(releaseVersion) {
  let changelog;

  try {
    changelog = readFileSync("CHANGELOG.md", "utf8");
  } catch {
    return "Automated release generated by Changesets.";
  }

  const lines = changelog.split(/\r?\n/);
  const sectionHeaderRegex = new RegExp(`^##\\s+\\[?${escapeRegExp(releaseVersion)}\\]?\\b`);

  let startIndex = -1;

  for (let index = 0; index < lines.length; index += 1) {
    if (sectionHeaderRegex.test(lines[index])) {
      startIndex = index;
      break;
    }
  }

  if (startIndex === -1) {
    return "Automated release generated by Changesets.";
  }

  let endIndex = lines.length;

  for (let index = startIndex + 1; index < lines.length; index += 1) {
    if (/^##\s+/.test(lines[index])) {
      endIndex = index;
      break;
    }
  }

  const section = lines.slice(startIndex, endIndex).join("\n").trim();
  return section || "Automated release generated by Changesets.";
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    stdio: "inherit",
    ...options,
  });

  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

function runQuiet(command, args) {
  const result = spawnSync(command, args, {
    stdio: "ignore",
    env: process.env,
  });

  return result.status === 0;
}
